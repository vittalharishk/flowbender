import { promises as fs } from "fs";
import path from "path";
import crypto from "crypto";
import { S3Client, PutObjectCommand, GetObjectCommand, DeleteObjectCommand } from "@aws-sdk/client-s3";

// File storage behind one small interface. When AWS_S3_BUCKET is set every file
// is stored in (and served from) that private S3 bucket; otherwise files live on
// the server's disk (UPLOAD_DIR, default frontend/uploads).

export interface StoredFile {
  key: string;
  url: string;
  name: string;
  size: number;
  contentType: string;
}

export interface FileStorage {
  save(data: Buffer, originalName: string, contentType: string, owner?: string): Promise<StoredFile>;
  read(key: string): Promise<{ data: Buffer; contentType: string } | null>;
  remove(key: string): Promise<void>;
}

export const MAX_UPLOAD_BYTES = 50 * 1024 * 1024;

const TYPES: Record<string, string> = {
  ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp", ".gif": "image/gif", ".svg": "image/svg+xml",
  ".pdf": "application/pdf", ".txt": "text/plain", ".csv": "text/csv", ".fdx": "application/xml", ".fountain": "text/plain",
  ".doc": "application/msword", ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  ".xls": "application/vnd.ms-excel", ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  ".ppt": "application/vnd.ms-powerpoint", ".pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
  ".mp3": "audio/mpeg", ".wav": "audio/wav", ".m4a": "audio/mp4", ".mp4": "video/mp4", ".mov": "video/quicktime", ".zip": "application/zip",
};

export function allowedExtension(name: string): string | null {
  const ext = path.extname(name).toLowerCase();
  return ext in TYPES ? ext : null;
}

// Keys are generated by us: [<account>/]<yyyy-mm>/<random>.<ext>. Anything else
// is rejected, which also blocks path traversal on read.
const KEY_PATTERN = /^(?:[a-z0-9][a-z0-9._-]{0,60}\/)?\d{4}-\d{2}\/[a-f0-9]{24}\.[a-z0-9]{2,8}$/;

// "harish@flowbender.app" -> "harish-at-flowbender.app" (a safe S3 folder name)
export function ownerFolder(owner: unknown): string {
  if (typeof owner !== "string") return "";
  const safe = owner.trim().toLowerCase().replace(/@/g, "-at-").replace(/[^a-z0-9._-]+/g, "-").replace(/^[-.]+|[-.]+$/g, "").slice(0, 60);
  return safe && /^[a-z0-9]/.test(safe) ? `${safe}/` : "";
}

class LocalDiskStorage implements FileStorage {
  constructor(private root: string) {}

  async save(data: Buffer, originalName: string, contentType: string, owner?: string): Promise<StoredFile> {
    const ext = allowedExtension(originalName);
    if (!ext) throw new Error("File type not allowed.");
    const key = ownerFolder(owner) + newKey(ext);
    const full = path.join(this.root, key);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, data);
    return { key, url: `/api/files/${key}`, name: originalName, size: data.length, contentType: TYPES[ext] || contentType };
  }

  async read(key: string) {
    if (!KEY_PATTERN.test(key)) return null;
    try {
      const data = await fs.readFile(path.join(this.root, key));
      return { data, contentType: TYPES[path.extname(key)] || "application/octet-stream" };
    } catch {
      return null;
    }
  }

  async remove(key: string) {
    if (!KEY_PATTERN.test(key)) return;
    await fs.rm(path.join(this.root, key), { force: true });
  }
}

function newKey(ext: string) {
  return `${new Date().toISOString().slice(0, 7)}/${crypto.randomBytes(12).toString("hex")}${ext}`;
}

class S3FileStorage implements FileStorage {
  private client: S3Client;
  constructor(private bucket: string, region: string) {
    this.client = new S3Client({ region });
  }

  async save(data: Buffer, originalName: string, contentType: string, owner?: string): Promise<StoredFile> {
    const ext = allowedExtension(originalName);
    if (!ext) throw new Error("File type not allowed.");
    const key = ownerFolder(owner) + newKey(ext);
    const type = TYPES[ext] || contentType;
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: data, ContentType: type }));
    return { key, url: `/api/files/${key}`, name: originalName, size: data.length, contentType: type };
  }

  async read(key: string) {
    if (!KEY_PATTERN.test(key)) return null;
    try {
      const result = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!result.Body) return null;
      const data = Buffer.from(await result.Body.transformToByteArray());
      return { data, contentType: TYPES[path.extname(key)] || result.ContentType || "application/octet-stream" };
    } catch (error) {
      if ((error as { name?: string }).name !== "NoSuchKey") console.error("[files] S3 read failed:", key, error);
      return null;
    }
  }

  async remove(key: string) {
    if (!KEY_PATTERN.test(key)) return;
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

let storage: FileStorage | undefined;
export function getFileStorage(): FileStorage {
  if (!storage) {
    const bucket = process.env.AWS_S3_BUCKET;
    storage = bucket
      ? new S3FileStorage(bucket, process.env.AWS_REGION || "ap-southeast-2")
      : new LocalDiskStorage(path.resolve(process.env.UPLOAD_DIR || path.join(process.cwd(), "uploads")));
  }
  return storage;
}
