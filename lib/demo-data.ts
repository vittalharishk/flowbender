let breakdownIndex = 1;
let equipmentIndex = 1;

function breakdown(
  category: SceneBreakdownItem["category"],
  name: string,
  notes?: string,
): SceneBreakdownItem {
  return {
    id: `bi-${String(breakdownIndex++).padStart(3, "0")}`,
    category,
    name,
    notes,
  };
}

function equipment(name: string, notes?: string): ShootDayEquipment {
  return {
    id: `eq-${String(equipmentIndex++).padStart(3, "0")}`,
    name,
    notes,
    imageUrl: getEquipmentImage({ name, notes }),
  };
}

function scheduleEntryId(dayId: string) {
  return `se-${dayId}`;
}

function formatScheduleSceneNumber(sceneNumber: string) {
  if (sceneNumber.startsWith("Sc.") || sceneNumber.startsWith("Ep")) {
    return sceneNumber;
  }

  return `Sc. ${sceneNumber}`;
}

function scheduleStatusFromShootDay(day: ShootDay): ScheduleEntry["status"] {
  switch (day.status) {
    case "completed":
      return "completed";
    case "cancelled":
      return "postponed";
    case "in-progress":
      return "shooting";
    default:
      return "scheduled";
  }
}

