function getVisualCategory(item: { name: string; category?: string }): string {
  const text = `${item.name} ${item.category ?? ""}`.toLowerCase();
  if (/\b(camera|cam|lens|ronin|drone|teradek)\b/.test(text)) return "camera";
  if (/\b(mic|microphone|lav|sound|audio|boom|recorder|mixer|timecode)\b/.test(text)) return "sound";
  if (/\b(monitor|screen|dit|video village|led wall)\b/.test(text)) return "monitoring";
  if (/\b(light|led|skypanel|fresnel|aputure|astera|neon|practical lighting)\b/.test(text)) return "lighting";
  if (/\b(rain|weather|safety|hazard|fog)\b/.test(text)) return "protection";
  if (/\b(dolly|dolly|jib|slider|grip|diffusion|floppy|apple box|camera block|silk|rig)\b/.test(text)) return "grip";
  if (/\b(costume|garment|wardrobe)\b/.test(text)) return "costume";
  if (/\b(makeup|mirror)\b/.test(text)) return "makeup";
  if (/\b(walkie|radio|communication)\b/.test(text)) return "communication";
  if (/\b(generator|power)\b/.test(text)) return "power";
  if (/\b(piano|music|recording)\b/.test(text)) return "music";
  return item.category?.toLowerCase().trim() || "default";
}

/**
 * Returns the best matching high-resolution image URL for any equipment item:
 * 1. Checks item.imageUrl (if set)
 * 2. Checks exact name lookup in equipmentImageReferences
 * 3. Checks case-insensitive name match
 * 4. Checks category fallback
 * 5. Returns default film equipment image
 */
export function getEquipmentImage(item: {
  name: string;
  category?: string;
  imageUrl?: string;
  notes?: string;
}): string {
  if (item.imageUrl && item.imageUrl.trim().length > 0) {
    // Demo records previously stored broad stock URLs directly on each item.
    // Keep a URL only when it was entered manually by the user.
    if (Object.values(equipmentImageReferences).includes(item.imageUrl)) {
      const visualCategory = getVisualCategory(item);
      return illustratedEquipmentImage(visualCategory) ?? getEquipmentFallback(visualCategory);
    }
    return item.imageUrl;
  }

  const visualCategory = getVisualCategory(item);
  const illustration = illustratedEquipmentImage(visualCategory);
  if (illustration) return illustration;

  if (equipmentImageReferences[item.name]) {
    return equipmentImageReferences[item.name];
  }

  // Case-insensitive match
  const lowerName = item.name.toLowerCase();
  for (const [key, url] of Object.entries(equipmentImageReferences)) {
    if (key.toLowerCase() === lowerName) {
      return url;
    }
  }

  // Partial match
  for (const [key, url] of Object.entries(equipmentImageReferences)) {
    if (lowerName.includes(key.toLowerCase()) || key.toLowerCase().includes(lowerName)) {
      return url;
    }
  }

  if (visualCategory !== "default" && categoryEquipmentFallbacks[visualCategory]) {
    return categoryEquipmentFallbacks[visualCategory];
  }

  return getEquipmentFallback(visualCategory);
}

/**
 * Returns the category-specific fallback image.
 */
export function getEquipmentFallback(category?: string): string {
  if (!category) return categoryEquipmentFallbacks.default;
  const lower = category.toLowerCase().trim();
  return categoryEquipmentFallbacks[lower] ?? categoryEquipmentFallbacks.default;
}
